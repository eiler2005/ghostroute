import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
const scope=vm.createContext({crypto:webcrypto,URL,Date,Map,Error,Math,Number});
vm.runInContext(readFileSync(new URL('../extension/diagnostics.js',import.meta.url),'utf8'),scope);
const Diagnostics=scope.GuardDiagnostics,wire=[];
let now=1000,readCount=0;
const fixture=()=>({request:{url:'https://fixture.example.org/private?credential=private-query',method:'POST',headers:[{name:'Authorization',value:'private-header'}],postData:{text:'private-request'}},response:{status:200,content:{mimeType:'application/json',size:120},headers:[{name:'Set-Cookie',value:'private-cookie'}]},time:24,getContent:callback=>{readCount++;callback('<script>globalThis.executed=true</script>'+ 'x'.repeat(2000),'');}});
const control=new Diagnostics(message=>wire.push(message),()=>now);
control.record(fixture());assert.equal(control.events.length,0);
control.visible=true;control.allow(true);assert.equal(control.start(),true);
control.record(fixture());assert.equal(readCount,0,'Read body without explicit request');
assert(!JSON.stringify(wire).includes('private-'),'HAR private fields leaked');
const event=control.events[0].event;
assert.equal((await control.preview(event)).length,1024);
assert.equal(readCount,1);assert.equal(wire.filter(e=>e.op==='preview').length,0,'Local preview was sent to app');
await control.command({action:'preview',session:control.session,event,id:'a'.repeat(32)});
assert.equal(wire.filter(e=>e.op==='preview').length,1);
const previousSession=control.session;control.hide();assert.equal(control.text,'');assert.equal(control.events.length,0);
assert.equal(await control.command({action:'start',session:previousSession}),false,'Hidden panel accepted app command');
control.visible=true;control.allow(true);control.start();
let deliver;
control.record({...fixture(),getContent:callback=>{deliver=callback;}});
const pending=control.preview(control.events[0].event);control.stop();deliver('late-response','');
await assert.rejects(pending);assert.equal(control.text,'','Late content reappeared after Stop');
control.start();control.record(fixture());control.navigated();assert.equal(control.events.length,0);
control.record(fixture());now+=61000;control.tick();assert.equal(control.events.length,0);assert.equal(control.requests.size,0);
assert.equal(control.text,'');
console.log('PASS: prepared tab scope, no unsolicited body/HAR leakage, bounded preview, hidden-panel revoke, late response rejection, navigation and timeout erasure');
